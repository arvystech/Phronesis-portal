  const classCounts = {};
  students.forEach(s => {
    classCounts[s.class] = (classCounts[s.class] || 0) + 1;
  });
  const classDistribution = Object.entries(classCounts).map(([className, count]) => ({
    class: className,
    count,
  }));

  const monthlyRevenue = [
    { month: 'Sep', revenue: 1850000 },
    { month: 'Oct', revenue: 2100000 },
    { month: 'Nov', revenue: 1450000 },
    { month: 'Dec', revenue: 980000 },
    { month: 'Jan', revenue: 2350000 },
    { month: 'Feb', revenue: 1720000 },
  ];

  return {
    stats: {
      total,
      pending,
      revenue,
      outstanding,
      approved,
      admitted,
      rejected,
    },
    monthlyRevenue,
    classDistribution,
    recentRegistrations: students.slice(0, 6),
  };
